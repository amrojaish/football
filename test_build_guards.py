#!/usr/bin/env python3
"""
Build guards (12 Nov 2026). No browser, no DB writes. Run:
    python C:\\Users\\User\\Projects\\Football\\test_build_guards.py
Needs make_assets.py run (sw.js ASSETS block).

  A  sw.js notification icon carries ?v=<sha1[:8] of icons/icon-192.png>, generated by make_assets (NOTIF_ICON);
     the hash changes when the icon file changes (temp copy, repo icon untouched)
  B  search instant index gate (make_search.check_top_size): ok below 90%, warning from 90%, build fails (SystemExit)
     above the limit with a clear message; the size vs limit line is printed; current search_top.js is within the limit
"""
import contextlib
import gzip
import hashlib
import io
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import make_assets  # noqa: E402
import make_search  # noqa: E402

fails = 0


def check(name, cond, extra=None):
    global fails
    print(("PASS " if cond else "FAIL ") + name + ("" if cond else f"  {extra!r}"[:600]))
    if not cond:
        fails += 1


# ── A) notification icon version ──
icon = ROOT / "icons" / "icon-192.png"
want = "/icons/icon-192.png?v=" + hashlib.sha1(icon.read_bytes()).hexdigest()[:8]
check("A notif_icon_url() = /icons/icon-192.png?v=<sha1[:8] of the file>", make_assets.notif_icon_url() == want,
      make_assets.notif_icon_url())
sw = (ROOT / "sw.js").read_text(encoding="utf-8")
m = re.search(r"const NOTIF_ICON = '([^']+)';", sw)
check("A sw.js ASSETS block has NOTIF_ICON for the current icon (run make_assets)", m and m.group(1) == want, m and m.group(1))
blk = re.search(r"/\* ASSETS-BEGIN.*?ASSETS-END \*/", sw, re.S)
check("A NOTIF_ICON is inside the generated ASSETS block", blk and "NOTIF_ICON" in blk.group(0))
check("A push handler uses NOTIF_ICON for icon fallback + badge, no bare icon path",
      "icon: d.icon || NOTIF_ICON" in sw and "badge: NOTIF_ICON" in sw and "badge: '/icons/" not in sw)
with tempfile.TemporaryDirectory() as td:
    tmp = Path(td) / "icon-192.png"
    shutil.copyfile(icon, tmp)
    v1 = make_assets.notif_icon_url(tmp)
    check("A same bytes -> same version", v1 == want, v1)
    tmp.write_bytes(tmp.read_bytes() + b"\0")
    v2 = make_assets.notif_icon_url(tmp)
    check("A icon changed -> version changes", v2 != v1 and re.fullmatch(r"/icons/icon-192\.png\?v=[0-9a-f]{8}", v2), [v1, v2])


# ── B) search instant index limit ──
def run(gz, limit=16 * 1024):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        try:
            return make_search.check_top_size(gz, limit), out.getvalue(), None
        except SystemExit as e:
            return None, out.getvalue(), e


L = make_search.TOP_LIMIT_GZ
check("B limit is 16 KB gzip (same as test_search_size), warn at 90%", L == 16 * 1024 and make_search.TOP_WARN == 0.9)
r, out, e = run(int(L * 0.5), L)
check("B 50% -> ok, prints size vs limit, no warning", r == "ok" and "/ limit 16.0 KB" in out and "WARNING" not in out, out)
r, out, e = run(-(-L * 9 // 10), L)   # ceil(90%)
check("B exactly 90% -> warning", r == "warn" and "WARNING" in out and "90%" in out, out)
r, out, e = run(L, L)
check("B exactly at the limit -> warning, not failure", r == "warn" and e is None, out)
r, out, e = run(L + 1, L)
check("B over the limit -> build fails (SystemExit) with a clear message",
      e is not None and "exceeds limit" in str(e.code) and str(L + 1) in str(e.code) and "not written" in str(e.code), e and e.code)
top = (ROOT / "assets" / "search_top.js").read_bytes()
cur = len(gzip.compress(top, 9))
check(f"B current search_top.js {cur} B gzip <= limit {L}", cur <= L, cur)
text = top.decode("utf-8").replace("\r\n", "\n")
check("B top_gz_size() measures the file as written (same as test_search_size)", make_search.top_gz_size(text) == cur,
      [make_search.top_gz_size(text), cur])
print(f"SIZE search_top.js gzip {cur} B = {cur / L:.0%} of {L} B")

print(f"\n{'ALL PASS' if not fails else f'FAILS: {fails}'}")
sys.exit(1 if fails else 0)
